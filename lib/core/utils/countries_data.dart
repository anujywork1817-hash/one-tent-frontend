    'ivory coast republic': 'ivory coast',
    'cote d\'ivoire': 'ivory coast',
    'burma': 'myanmar',
    'holland': 'netherlands',
  };

  static String? _canonicalCountry(String input) {
    final key = input.trim().toLowerCase();
    if (countryToDemonym.containsKey(key)) return key;
    if (_aliases.containsKey(key)) return _aliases[key];
    return null;
  }

  /// Returns the canonical country key for [input], matching either a
  /// country name or its demonym (e.g. "India" or "Indian" both resolve to
  /// "india"), or null if it isn't a recognized country/nationality.
  static String? resolveCountry(String input) {
    final byName = _canonicalCountry(input);
    if (byName != null) return byName;

    final key = input.trim().toLowerCase();
    for (final entry in countryToDemonym.entries) {
      if (entry.value.toLowerCase() == key) return entry.key;
    }
    return null;
  }

  static bool isValidCountry(String input) => resolveCountry(input) != null;

  static bool isValidNationality(String input) => resolveCountry(input) != null;
