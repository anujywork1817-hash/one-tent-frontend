  /// Common short forms / aliases that resolve to a canonical country key.
  static const Map<String, String> _aliases = {
    'usa': 'united states',
    'us': 'united states',
    'america': 'united states',
    'uk': 'united kingdom',
    'britain': 'united kingdom',
